const dictionaries: Record<AppLocale, Record<TranslationKey, string>> = {
  bs,
  en,
};

export function translate(locale: AppLocale, key: TranslationKey): string {
  return dictionaries[locale][key] ?? dictionaries.bs[key] ?? key;
}

export function motivationKey(
  bucket: 'great' | 'solid' | 'restart',
  seed: string,
): TranslationKey {
  const keys: Record<'great' | 'solid' | 'restart', TranslationKey[]> = {
    great: ['motivationGreat1', 'motivationGreat2', 'motivationGreat3'],
    solid: ['motivationSolid1', 'motivationSolid2', 'motivationSolid3'],
    restart: ['motivationRestart1', 'motivationRestart2', 'motivationRestart3'],
  };
  const list = keys[bucket];
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) {
    hash = (hash + seed.charCodeAt(i) * (i + 1)) % list.length;
  }
  return list[hash]!;
}
